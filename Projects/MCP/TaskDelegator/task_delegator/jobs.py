"""Provider-agnostic background jobs, persisted on disk.

Every job lives in its own folder under the state dir:

    job.json        metadata written at launch (+ cancel flag)
    prompt.txt      the exact instructions sent to the agent (fed via stdin)
    stdout.log      the agent's stdout (for Codex: the JSONL event stream)
    stderr.log      the agent's stderr
    exit.json       written by the watcher thread when the process exits

Status is always derived from these files plus a liveness check of the PID, so
a job is still inspectable after the MCP server restarts (the agent process
itself keeps running and keeps writing its files).
"""

from __future__ import annotations

import json
import os
import secrets
import shutil
import subprocess
import threading
import time
from datetime import datetime
from pathlib import Path
from typing import Any, Callable

from . import procs

STATE_ROOT = Path(
    os.environ.get("TASK_DELEGATOR_STATE_DIR")
    or Path(os.environ.get("LOCALAPPDATA") or Path.home()) / "TaskDelegator"
)
JOBS_DIR = STATE_ROOT / "jobs"

# job_id -> Popen, only for jobs launched by this server process.
_procs: dict[str, subprocess.Popen] = {}
_lock = threading.Lock()


def now_iso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def new_job_id(provider: str) -> str:
    return f"{provider}-{time.strftime('%Y%m%d-%H%M%S')}-{secrets.token_hex(2)}"


def job_dir(job_id: str) -> Path:
    # Job ids are generated by us; reject anything that could escape JOBS_DIR.
    if not job_id or any(c in job_id for c in "/\\:") or job_id in (".", ".."):
        raise ValueError(f"invalid job id: {job_id!r}")
    return JOBS_DIR / job_id


def write_json(path: Path, data: Any) -> None:
    """Atomic write. Safe when several threads write or read the same file at once."""
    # A temp name per writer: two threads writing one file must not share (and steal) one temp file.
    tmp = path.with_name(f"{path.name}.{os.getpid()}.{threading.get_ident()}.tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    for attempt in range(10):
        try:
            os.replace(tmp, path)
            return
        except PermissionError:
            # Windows refuses to replace a file another thread or process holds open for a moment
            # (a concurrent read_json, an antivirus scan): WinError 5 / 32. Wait and retry.
            if attempt == 9:
                try:
                    tmp.unlink()
                except OSError:
                    pass
                raise
            time.sleep(0.02 * (attempt + 1))


def read_json(path: Path, default: Any = None) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return default


def load_meta(job_id: str) -> dict:
    meta = read_json(job_dir(job_id) / "job.json")
    if meta is None:
        raise KeyError(f"unknown job: {job_id}")
    return meta


def update_meta(job_id: str, **fields: Any) -> dict:
    with _lock:
        meta = load_meta(job_id)
        meta.update(fields)
        write_json(job_dir(job_id) / "job.json", meta)
        return meta


def create_job(provider: str, prompt: str, meta: dict) -> tuple[str, Path]:
    JOBS_DIR.mkdir(parents=True, exist_ok=True)
    job_id = new_job_id(provider)
    d = job_dir(job_id)
    d.mkdir(parents=True, exist_ok=False)
    # No BOM: agents read stdin as raw UTF-8.
    (d / "prompt.txt").write_bytes(prompt.encode("utf-8"))
    write_json(d / "job.json", {"job_id": job_id, "provider": provider, "created_at": now_iso(), **meta})
    return job_id, d


def launch(job_id: str, argv: list[str], cwd: str, env: dict[str, str],
           on_exit: "Callable[[str], None] | None" = None) -> int:
    """Start the agent process for a prepared job. Returns its PID.

    `on_exit(job_id)` runs in the watcher thread right after exit.json is written
    (best effort: errors are swallowed, and it does not run if this process dies first).
    """
    d = job_dir(job_id)
    with open(d / "prompt.txt", "rb") as fin, open(d / "stdout.log", "wb") as fout, open(
        d / "stderr.log", "wb"
    ) as ferr:
        proc = subprocess.Popen(
            argv,
            cwd=cwd,
            env=env,
            stdin=fin,
            stdout=fout,
            stderr=ferr,
            creationflags=procs.POPEN_FLAGS,
            close_fds=True,
        )
    # The child holds its own copies of the handles; ours are closed by the `with`.
    with _lock:
        _procs[job_id] = proc
    # While we hold the Popen handle the PID cannot be recycled, so this reads OUR process.
    update_meta(
        job_id,
        pid=proc.pid,
        pid_created=procs.process_created(proc.pid),
        image=os.path.basename(argv[0]),
        started_at=now_iso(),
        argv=argv,
    )

    def _watch() -> None:
        code = proc.wait()
        write_json(d / "exit.json", {"exit_code": code, "finished_at": now_iso()})
        with _lock:
            _procs.pop(job_id, None)
        if on_exit is not None:
            try:
                on_exit(job_id)
            except Exception:  # noqa: BLE001 - a bookkeeping hook must never kill the watcher
                pass

    threading.Thread(target=_watch, name=f"watch-{job_id}", daemon=True).start()
    return proc.pid


def _same_process_alive(meta: dict) -> bool:
    return procs.pid_alive(meta.get("pid"), meta.get("image"), meta.get("pid_created"))


def is_running(job_id: str, meta: dict) -> bool:
    if (job_dir(job_id) / "exit.json").exists():
        return False
    with _lock:
        proc = _procs.get(job_id)
    if proc is not None:
        # Watched by this server: report running until the watcher has recorded the exit,
        # so callers never see the gap between process exit and exit.json.
        return True
    return _same_process_alive(meta)


def finalize_unobserved(job_id: str) -> dict | None:
    """Persist the end of a job whose process exited while no server was watching it.

    Without this the job would be re-probed by PID forever (and a recycled PID could
    make it look alive again). Returns the exit record, or None if it is still running
    or is watched by this server.
    """
    d = job_dir(job_id)
    with _lock:
        if job_id in _procs or (d / "exit.json").exists():
            return read_json(d / "exit.json")
        meta = read_json(d / "job.json") or {}
        if not meta.get("pid") or _same_process_alive(meta):
            return None
        record = {"exit_code": None, "finished_at": now_iso(), "unobserved": True}
        write_json(d / "exit.json", record)
        return record


def cancel(job_id: str) -> tuple[bool, str]:
    meta = update_meta(job_id, cancel_requested=True, cancelled_at=now_iso())
    pid = meta.get("pid")
    if not pid:
        return False, "job has no pid"
    with _lock:
        proc = _procs.get(job_id)
    # Never kill by a bare PID: it may belong to an unrelated process by now.
    if proc is None and not _same_process_alive(meta):
        return False, "process already gone"
    if proc is not None and proc.poll() is not None:
        return False, "process already exited"
    return procs.kill_tree(int(pid))


def list_job_ids(provider: str | None = None, limit: int = 20) -> list[str]:
    if not JOBS_DIR.exists():
        return []
    ids = [p.name for p in JOBS_DIR.iterdir() if p.is_dir() and (p / "job.json").exists()]
    if provider:
        ids = [i for i in ids if i.startswith(provider + "-")]
    # Ids embed a sortable timestamp right after the provider prefix.
    ids.sort(key=lambda i: i.split("-", 1)[-1], reverse=True)
    return ids[:limit]


def cleanup_old(max_age_days: int) -> int:
    """Delete finished job folders older than `max_age_days`. Returns how many were removed.

    Jobs that ended while no server was watching are finalized first, so they age out too.
    """
    if not JOBS_DIR.exists() or max_age_days <= 0:
        return 0
    cutoff = time.time() - max_age_days * 86400
    removed = 0
    for p in JOBS_DIR.iterdir():
        try:
            if not p.is_dir() or not (p / "job.json").exists():
                continue
            if (p / "job.json").stat().st_mtime >= cutoff:
                continue
            if not (p / "exit.json").exists() and finalize_unobserved(p.name) is None:
                continue  # still running
            shutil.rmtree(p, ignore_errors=True)
            removed += 1
        except (OSError, ValueError):
            pass
    return removed


def tail_text(path: Path, max_chars: int) -> str:
    try:
        data = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    return data[-max_chars:]
